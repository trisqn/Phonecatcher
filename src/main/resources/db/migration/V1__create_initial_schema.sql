CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_app_user_role CHECK (role IN ('USER', 'MODERATOR', 'ADMIN'))
);

CREATE UNIQUE INDEX ux_app_user_email_lower ON app_user (LOWER(email));

CREATE TABLE phone_number (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalized_number VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_phone_number_normalized_number UNIQUE (normalized_number)
);

CREATE TABLE fraud_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    warning_title VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_fraud_category_code UNIQUE (code)
);

CREATE TABLE report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES app_user (id),
    phone_number_id BIGINT NOT NULL REFERENCES phone_number (id),
    category_id BIGINT NOT NULL REFERENCES fraud_category (id),
    incident_date DATE NOT NULL,
    incident_time TIME,
    communication_channel VARCHAR(30) NOT NULL,
    description VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_report_communication_channel
        CHECK (communication_channel IN ('PHONE_CALL', 'SMS', 'MESSAGING_APP', 'EMAIL', 'OTHER'))
);

CREATE INDEX ix_report_phone_number_id ON report (phone_number_id);
CREATE INDEX ix_report_reporter_id ON report (reporter_id);
CREATE INDEX ix_report_created_at ON report (created_at);

CREATE TABLE warning (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number_id BIGINT NOT NULL REFERENCES phone_number (id),
    dominant_category_id BIGINT NOT NULL REFERENCES fraud_category (id),
    title VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL,
    activated_at TIMESTAMPTZ NOT NULL,
    deactivated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_warning_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'WITHDRAWN')),
    CONSTRAINT ck_warning_deactivation_time CHECK (
        (status = 'ACTIVE' AND deactivated_at IS NULL)
        OR (status IN ('EXPIRED', 'WITHDRAWN') AND deactivated_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX ux_warning_active_phone_number
    ON warning (phone_number_id)
    WHERE status = 'ACTIVE';
CREATE INDEX ix_warning_phone_number_id ON warning (phone_number_id);
CREATE INDEX ix_warning_status ON warning (status);
CREATE INDEX ix_warning_updated_at ON warning (updated_at);

CREATE TABLE dispute (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warning_id BIGINT NOT NULL REFERENCES warning (id),
    submitter_id BIGINT NOT NULL REFERENCES app_user (id),
    reviewer_id BIGINT REFERENCES app_user (id),
    reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
    review_comment TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT ck_dispute_status CHECK (status IN ('SUBMITTED', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_dispute_review_state CHECK (
        (status = 'SUBMITTED' AND reviewer_id IS NULL AND reviewed_at IS NULL)
        OR (status IN ('ACCEPTED', 'REJECTED') AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX ux_dispute_submitted_warning_submitter
    ON dispute (warning_id, submitter_id)
    WHERE status = 'SUBMITTED';
CREATE INDEX ix_dispute_warning_id ON dispute (warning_id);
CREATE INDEX ix_dispute_status ON dispute (status);
